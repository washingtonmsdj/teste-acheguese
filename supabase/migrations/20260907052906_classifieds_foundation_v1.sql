-- Applied to the isolated acheguese-v2 project.
create schema if not exists private;

create table if not exists public.cities (
  id bigint generated by default as identity primary key,
  ibge_code integer unique,
  state_code text not null check (char_length(state_code) = 2),
  name text not null check (char_length(name) between 2 and 120),
  slug text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (state_code, slug)
);

create table if not exists public.classified_categories (
  id text primary key,
  label text not null check (char_length(label) between 2 and 80),
  sort_order smallint not null default 0,
  is_active boolean not null default true
);

