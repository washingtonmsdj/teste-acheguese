create table if not exists public.classifieds (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  category_id text not null references public.classified_categories(id),
  city_id bigint not null references public.cities(id),
  slug text not null unique,
  title text not null check (char_length(title) between 5 and 120),
  description text not null check (char_length(description) between 20 and 5000),
  condition text not null check (condition in ('new', 'like_new', 'used', 'for_parts')),
  price_cents bigint check (price_cents is null or price_cents >= 0),
  currency text not null default 'BRL' check (currency = 'BRL'),
  neighborhood text check (neighborhood is null or char_length(neighborhood) <= 120),
  status text not null default 'draft'
    check (status in ('draft', 'pending_review', 'published', 'paused', 'sold', 'rejected', 'archived')),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  search_vector tsvector generated always as (
    to_tsvector(
      'portuguese',
      coalesce(title, '') || ' ' || coalesce(description, '') || ' ' || coalesce(neighborhood, '')
    )
  ) stored,
  check (
    (status = 'published' and published_at is not null)
    or status <> 'published'
  )
);

create table if not exists private.classified_locations (
  classified_id uuid primary key references public.classifieds(id) on delete cascade,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  accuracy_meters integer check (accuracy_meters is null or accuracy_meters >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.classified_media (
  id uuid primary key default gen_random_uuid(),
  classified_id uuid not null references public.classifieds(id) on delete cascade,
  storage_key text not null unique,
  alt text not null default '' check (char_length(alt) <= 200),
  position smallint not null check (position between 0 and 9),
  created_at timestamptz not null default now(),
  unique (classified_id, position)
);

create table if not exists public.classified_favorites (
  user_id uuid not null references auth.users(id) on delete cascade,
  classified_id uuid not null references public.classifieds(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, classified_id)
);

create table if not exists public.classified_reports (
  id uuid primary key default gen_random_uuid(),
  classified_id uuid not null references public.classifieds(id) on delete cascade,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  reason text not null
    check (reason in ('fraud', 'prohibited', 'duplicate', 'wrong_category', 'harassment', 'other')),
  details text check (details is null or char_length(details) <= 2000),
  created_at timestamptz not null default now(),
  unique (classified_id, reporter_id)
);

create table if not exists private.classified_moderation (
  classified_id uuid primary key references public.classifieds(id) on delete cascade,
  reviewer_id uuid references auth.users(id) on delete set null,
  decision text check (decision in ('approved', 'rejected', 'needs_changes')),
  internal_notes text,
  reviewed_at timestamptz
);

create index if not exists classifieds_owner_updated_idx
  on public.classifieds (owner_id, updated_at desc);

create index if not exists classifieds_public_feed_idx
  on public.classifieds (city_id, published_at desc)
  where status = 'published';

create index if not exists classifieds_category_feed_idx
  on public.classifieds (category_id, city_id, published_at desc)
  where status = 'published';

create index if not exists classifieds_search_idx
  on public.classifieds using gin (search_vector);

create index if not exists classified_media_parent_idx
  on public.classified_media (classified_id, position);

create index if not exists classified_reports_parent_idx
  on public.classified_reports (classified_id, created_at desc);

create or replace function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

revoke all on function private.set_updated_at() from public;

drop trigger if exists classifieds_set_updated_at on public.classifieds;
create trigger classifieds_set_updated_at
before update on public.classifieds
for each row
execute function private.set_updated_at();

