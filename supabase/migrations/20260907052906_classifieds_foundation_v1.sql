create policy "Active cities are public"
on public.cities
for select
to anon, authenticated
using (is_active = true);

create policy "Active classified categories are public"
on public.classified_categories
for select
to anon, authenticated
using (is_active = true);

create policy "Published classifieds are public"
on public.classifieds
for select
to anon, authenticated
using (
  status = 'published'
  and published_at is not null
  and published_at <= now()
);

create policy "Owners can read their classifieds"
on public.classifieds
for select
to authenticated
using (
  (select auth.uid()) is not null
  and (select auth.uid()) = owner_id
);

create policy "Owners can create draft classifieds"
on public.classifieds
for insert
to authenticated
with check (
  (select auth.uid()) is not null
  and (select auth.uid()) = owner_id
  and status = 'draft'
  and published_at is null
);

create policy "Owners can update their classifieds"
on public.classifieds
for update
to authenticated
using (
  (select auth.uid()) is not null
  and (select auth.uid()) = owner_id
)
with check (
  (select auth.uid()) = owner_id
  and status in ('draft', 'pending_review', 'paused', 'sold', 'archived')
  and (
    status <> 'draft'
    or published_at is null
  )
);

create policy "Owners can delete their classifieds"
on public.classifieds
for delete
to authenticated
using (
  (select auth.uid()) is not null
  and (select auth.uid()) = owner_id
);

create policy "Published classified media is public"
on public.classified_media
for select
to anon, authenticated
using (
  exists (
    select 1
    from public.classifieds c
    where c.id = classified_id
      and c.status = 'published'
      and c.published_at is not null
      and c.published_at <= now()
  )
);

